"""Aggregate results into results/report_data.json (for demo/index.html) and results/summary.md (tables).

    python -m src.report
"""
from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent
RES = ROOT / "results"
ORDER = ["F", "A", "D", "B", "S", "L", "C"]
NAMES = {"F": "Fixed 500, no overlap", "A": "Fixed 500 + overlap 50", "D": "Recursive 800/80",
         "B": "Document structure", "S": "Semantic (similarity breaks)", "L": "Agentic LLM (Haiku, sample)",
         "C": "Structure + metadata filter"}


def _csv(name: str) -> list[dict]:
    p = RES / "manual" / name
    return list(csv.DictReader(p.open(encoding="utf-8"))) if p.exists() else []


def build() -> dict:
    cfg = json.loads((REPO / "configs" / "strategies.json").read_text(encoding="utf-8"))
    summary = json.loads((RES / "summary.json").read_text(encoding="utf-8"))
    ingest = json.loads((RES / "ingest_report.json").read_text(encoding="utf-8"))
    llm = json.loads((ROOT / "data/processed/llm_boundaries.json").read_text(encoding="utf-8")).get("summary", {})
    retrieval = {}
    for mk, s in summary.items():
        retrieval[mk] = {}
        for st in ORDER:
            row = {}
            for sp in ("dev", "test"):
                v = s.get(f"{st}/{sp}")
                if v:
                    row[sp] = {k: v[k] for k in ("n", "hit1", "hit3", "evidence_split", "filter_q", "filter_ok")}
            retrieval[mk][st] = row
    coh, gro, meta = defaultdict(list), defaultdict(list), defaultdict(lambda: [0, 0])
    for r in _csv("coherence_labels.csv"):
        coh[r["strategy"]].append(int(r["score_0_2"]))
    for r in _csv("grounding_labels_test.csv"):
        gro[r["strategy"]].append(int(r["score_0_2"]))
    for r in _csv("metadata_audit_test.csv"):
        meta[r["strategy"]][0] += r["complete_and_correct_incl_article"] == "True"
        meta[r["strategy"]][1] += 1
    manual = {st: {"coherence_mean": round(sum(coh[st]) / len(coh[st]), 2) if coh[st] else None, "coherence_n": len(coh[st]),
                   "grounding_counts": [gro[st].count(i) for i in (0, 1, 2)] if gro[st] else None,
                   "grounding_mean": round(sum(gro[st]) / len(gro[st]), 2) if gro[st] else None,
                   "metadata_ok": meta[st][0], "metadata_n": meta[st][1]} for st in ORDER}
    manual["C"]["coherence_mean"] = manual["B"]["coherence_mean"]   # same chunks as B
    manual["C"]["coherence_n"] = manual["B"]["coherence_n"]
    return {"strategies": [{"key": k, "name": NAMES[k], "config": cfg.get(k, {})} for k in ORDER],
            "models": cfg["models"], "retrieval": retrieval, "chunk_stats": ingest.get("chunk_stats", {}),
            "ingest": {k: v for k, v in ingest.get("models", {}).items()}, "manual_bge": manual, "llm_chunking": llm}


def markdown(d: dict) -> str:
    out = ["# Results summary (generated by `python -m src.report`)", ""]
    for m in d["models"]:
        r = d["retrieval"].get(m["key"])
        if not r:
            continue
        out += [f"## {m['name']} ({m['dims']} dims)", "",
                "| Strategy | Dev Hit@1 | Dev Evidence Hit@3 | Test Hit@1 | Test Evidence Hit@3 | Filter respected (dev+test) | Chunks | Embed s |",
                "|---|---|---|---|---|---|---|---|"]
        ing = d["ingest"].get(m["key"], {}).get("strategies", {})
        for st in ORDER:
            row = r.get(st, {})
            dv, ts = row.get("dev", {}), row.get("test", {})
            fq = dv.get("filter_q", 0) + ts.get("filter_q", 0)
            fo = dv.get("filter_ok", 0) + ts.get("filter_ok", 0)
            idx = "B" if st == "C" else st
            out.append(f"| {st} · {NAMES[st]} | {dv.get('hit1','-')}/{dv.get('n','-')} | {dv.get('hit3','-')}/{dv.get('n','-')} | "
                       f"{ts.get('hit1','-')}/{ts.get('n','-')} | {ts.get('hit3','-')}/{ts.get('n','-')} | "
                       f"{f'{fo}/{fq}' if fq else 'N/A'} | {ing.get(idx, {}).get('chunks','-')} | {ing.get(idx, {}).get('embed_seconds','-')} |")
        out.append("")
    out += ["## Manual audit (model bge-small)", "",
            "| Strategy | Coherence mean /2 (n) | Metadata complete & correct, test top-3 | Grounding 0/1/2 (test) | Grounding mean /2 |",
            "|---|---|---|---|---|"]
    for st in ORDER:
        x = d["manual_bge"][st]
        g = x["grounding_counts"]
        out.append(f"| {st} · {NAMES[st]} | {x['coherence_mean']} ({x['coherence_n']}) | {x['metadata_ok']}/{x['metadata_n']} | "
                   f"{'/'.join(map(str, g)) if g else '-'} | {x['grounding_mean']} |")
    out += ["", f"LLM chunking (strategy L): {json.dumps(d['llm_chunking'], ensure_ascii=False)}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    data = build()
    (RES / "report_data.json").write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    (RES / "summary.md").write_text(markdown(data), encoding="utf-8")
    print(markdown(data))
